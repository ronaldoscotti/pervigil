/** Pure so it can be tested without a DOM: `saved` is whatever `localStorage` held,
 *  `browser` whatever `navigator.language` reports. */
export function detectLang(saved: string | null, browser: string): Lang {
  if (saved && LANGS.includes(saved as Lang)) return saved as Lang;
  const prefix = browser.toLowerCase().slice(0, 2) as Lang;
  return LANGS.includes(prefix) ? prefix : "en";
}

let current: Lang = "en";

export const lang = () => current;

export function setLang(next: Lang) {
  current = next;
}

/** English is the floor, and an unknown key returns itself — a missing translation
 *  degrades to a readable word, never to a blank. */
export function t(key: string, params?: Record<string, string | number>): string {
  let value = STRINGS[current][key] ?? STRINGS.en[key] ?? key;
  if (params) {
    for (const [name, sub] of Object.entries(params)) {
      value = value.replace(`{${name}}`, String(sub));
    }
  }
  return value;
}
